import { test, expect } from '@playwright/test';

test('lesson notebook and persistent progress and backup shortcuts open their destinations', async ({ page }) => {
  let posts = 0;
  page.on('request', request => { if (request.method() === 'POST') posts++; });
  await page.goto('/?lesson=12');
  await page.getByRole('link', { name: 'Open notebook', exact: true }).click();
  const notebook = page.locator('#lesson-notebook-12');
  await expect(notebook).toHaveAttribute('open', '');
  await expect(notebook).toBeFocused();
  await notebook.getByRole('textbox').fill('Shortcut test: local note.');
  await notebook.getByRole('button', { name: 'Save note', exact: true }).click();
  await page.locator('.sidebar').getByRole('link', { name: 'Course progress', exact: true }).click();
  await expect(page.locator('#course-progress')).toBeFocused();
  await page.getByRole('button', { name: 'Open learning backup', exact: true }).click();
  await expect(page.locator('#course-learning-backup')).toBeFocused();
  await expect(page.getByRole('button', { name: 'Download learning backup' })).toBeVisible();
  await page.goto('/?lesson=65');
  await page.locator('.sidebar').getByRole('link', { name: 'Back up or restore', exact: true }).click();
  await expect(page.locator('#course-learning-backup')).toBeFocused();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download learning backup' }).click();
  expect((await downloadEvent).suggestedFilename()).toBe('managed-agents-learning-backup.json');
  expect(posts).toBe(0);
});

test('mobile menu opens notebook and backup without starting a run', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/?lesson=65');
  await page.screenshot({ path: 'artifacts/learning-guide/direct-sections-mobile.png' });
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  const menu = page.getByRole('dialog', { name: 'Course navigation' });
  await menu.getByRole('link', { name: 'Notebook / Lab 65', exact: true }).click();
  await expect(menu).not.toBeVisible();
  await expect(page.locator('#lesson-notebook-65')).toBeFocused();
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await menu.getByRole('link', { name: 'Checklist / Lab 65', exact: true }).click();
  await expect(menu).not.toBeVisible();
  await expect(page.locator('#lesson-checklist-65')).toBeFocused();
  await expect(page.locator('#lesson-checklist-65')).toHaveAttribute('open', '');
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await menu.getByRole('link', { name: 'Exercise / Lab 65', exact: true }).click();
  await expect(menu).not.toBeVisible();
  await expect(page.getByRole('tab', { name: 'Run the exercise', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Menu', exact: true }).click();
  await menu.getByRole('link', { name: 'Back up or restore', exact: true }).click();
  await expect(menu).not.toBeVisible();
  await expect(page.locator('#course-learning-backup')).toBeFocused();
  await expect(page.getByRole('button', { name: 'Download learning backup' })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/learning-guide-shortcuts-mobile.png' });
});

test('lesson section links survive reload, new tabs and browser history without changing learning state', async ({ page, context }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  let posts = 0; context.on('request', request => { if (request.method() === 'POST') posts++; });
  await page.goto('/?lesson=12');
  await page.screenshot({ path: 'artifacts/learning-guide/direct-sections-desktop.png' });
  await page.getByRole('link', { name: 'Open notebook', exact: true }).click();
  await expect(page).toHaveURL(/lesson=12#lesson-notebook-12$/);
  await page.locator('#lesson-notebook-12 textarea').fill('Keep this lesson note.');
  await page.getByRole('button', { name: 'Save note', exact: true }).click();
  await page.getByRole('link', { name: 'Open checklist', exact: true }).click();
  await expect(page.locator('#lesson-checklist-12')).toBeFocused();
  await expect(page.locator('#lesson-checklist-12 input:checked')).toHaveCount(0);
  await page.getByRole('link', { name: 'Open exercise', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Run the exercise', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.goBack();
  await expect(page.locator('#lesson-checklist-12')).toBeFocused();
  await page.reload();
  await expect(page.locator('#lesson-checklist-12')).toBeFocused();
  await expect(page.locator('#lesson-checklist-12')).toHaveAttribute('open', '');
  const opened = await context.newPage();
  await opened.goto((await page.getByRole('link', { name: 'Open notebook', exact: true }).getAttribute('href'))!);
  await expect(opened.locator('#lesson-notebook-12')).toBeFocused();
  await expect(opened.locator('#lesson-notebook-12 textarea')).toHaveValue('Keep this lesson note.');
  await opened.close();
  await page.getByRole('link', { name: 'Open exercise', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('tab', { name: 'Run the exercise', exact: true })).toBeFocused();
  await expect(page.getByRole('tab', { name: 'Run the exercise', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.locator('.sidebar').getByRole('button', { name: 'Lesson order', exact: true }).click();
  await page.locator('.sidebar').getByRole('link', { name: /Session options/ }).click();
  await expect(page).toHaveURL(/\?lesson=2$/);
  expect(posts).toBe(0);
});

test('Course progress opens the selected lesson section directly, including a different lesson', async ({ page }) => {
  await page.goto('/');
  const progress = page.getByRole('region', { name: 'Course progress', exact: true });
  await progress.getByRole('link', { name: 'Checklist for Lab 01', exact: true }).click();
  await expect(page.locator('#lesson-checklist-1')).toBeFocused();
  await page.locator('.sidebar').getByRole('link', { name: 'Course progress', exact: true }).click();
  await progress.getByText('Review lesson checklists', { exact: true }).click();
  await progress.getByRole('navigation', { name: 'Lab 65 sections', exact: true }).getByRole('link', { name: 'Notebook', exact: true }).click();
  await expect(page.locator('#lesson-notebook-65')).toBeFocused();
  await expect(page.locator('#lesson-notebook-65')).toHaveAttribute('open', '');
});
